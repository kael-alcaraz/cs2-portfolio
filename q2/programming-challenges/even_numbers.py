# Code 1:	Even Numbers

for i in range (2, 21):
	if i % 2 == 1:
		continue
  # I decided to display the use of the continue and modulo built-in function of Python, instead of a 3-parameter range, as it feels more natural to me.
	else:
		print(i)
  # This displays the number shown, which is a multiple of 2.
